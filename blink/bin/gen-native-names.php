<?php

// Generates internal/fixer/rules/native_names_gen.go, the lists PHP-CS-Fixer
// reads at runtime (see "Native functions and constants" in README.md).

declare(strict_types=1);

$functions = get_defined_functions()['internal'];
$functions = array_map('strtolower', $functions);
$functions = array_values(array_unique($functions));
sort($functions, SORT_STRING);

$constants = [];
$categories = get_defined_constants(true);
unset($categories['user']);
foreach ($categories as $names) {
    foreach (array_keys($names) as $name) {
        $constants[] = (string) $name;
    }
}
$constants = array_values(array_unique($constants));
sort($constants, SORT_STRING);

$extensions = get_loaded_extensions();
sort($extensions, SORT_STRING | SORT_FLAG_CASE);

$quote = static function (string $value): string {
    return '"' . addcslashes($value, "\"\\\0..\37\177") . '"';
};

$out = "// Code generated by bin/gen-native-names.php; DO NOT EDIT.\n\n";
$out .= "package rules\n\n";
$out .= '// Generated from PHP ' . PHP_VERSION . " with the extensions:\n";
foreach (array_chunk($extensions, 12) as $chunk) {
    $out .= '// ' . implode(', ', $chunk) . "\n";
}
$out .= "//\n// Regenerate with: php bin/gen-native-names.php > internal/fixer/rules/native_names_gen.go\n\n";
$out .= '// nativeFunctionNamesPHPVersion is the PHP version the lists below come from.' . "\n";
$out .= 'const nativeFunctionNamesPHPVersion = ' . $quote(PHP_VERSION) . "\n\n";
$out .= "// nativeInternalFunctionNames is get_defined_functions()['internal'], lowercased and sorted.\n";
$out .= "var nativeInternalFunctionNames = []string{\n";
foreach ($functions as $name) {
    $out .= "\t" . $quote($name) . ",\n";
}
$out .= "}\n\n";
$out .= "// nativeBuiltInConstantNames is every get_defined_constants(true) name outside the\n";
$out .= "// \"user\" category, case preserved (constant names are case-sensitive), sorted.\n";
$out .= "var nativeBuiltInConstantNames = []string{\n";
foreach ($constants as $name) {
    $out .= "\t" . $quote($name) . ",\n";
}
$out .= "}\n";

echo $out;
