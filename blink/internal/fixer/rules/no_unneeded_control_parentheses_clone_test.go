package rules

import "testing"

// The expected output of every case comes from the PHP engine.
func TestNoUnneededControlParenthesesClone(t *testing.T) {
	t.Parallel()
	cases := []struct{ src, want string }{
		{"$r = clone ($a);", "$r = clone $a;"},
		{"$r = clone($a);", "$r = clone $a;"},
		{"$r = clone ( $a );", "$r = clone  $a ;"},
		{"$r = clone (($a));", "$r = clone $a;"},
		{"$r = clone (($a ?: $b));", "$r = clone ($a ?: $b);"},
		{"$r = clone ($a->b);", "$r = clone $a->b;"},
		{"$r = clone ($a::$b);", "$r = clone $a::$b;"},
		{"$r = clone ($a[0]);", "$r = clone $a[0];"},
		{"$r = clone (foo());", "$r = clone foo();"},
		{"$r = clone (new Foo());", "$r = clone new Foo();"},
		{"$r = clone (new Foo);", "$r = clone new Foo;"},
		{"$r = clone (new Foo(1 + 2));", "$r = clone new Foo(1 + 2);"},
		{"$r = clone (Foo::bar());", "$r = clone Foo::bar();"},
		{"$r = clone (\\Foo\\bar());", "$r = clone \\Foo\\bar();"},
		{"$r = clone ($a ?: $b);", "$r = clone ($a ?: $b);"},
		{"$r = clone ($a ?? $b);", "$r = clone ($a ?? $b);"},
		{"$r = clone ($f ? $a : $b);", "$r = clone ($f ? $a : $b);"},
		{"$r = clone ($a, ['x' => 1]);", "$r = clone ($a, ['x' => 1]);"},
		{"$r = clone ($a, ['x' => 1],);", "$r = clone ($a, ['x' => 1],);"},
		{"$r = clone (object: $a, withProperties: ['x' => 1]);", "$r = clone (object: $a, withProperties: ['x' => 1]);"},
		{"$r = clone(...);", "$r = clone(...);"},
		{"$r = clone ($a)->b;", "$r = clone ($a)->b;"},
		{"$r = $f ? clone ($a) : $b;", "$r = $f ? clone $a : $b;"},
		{"$r = $f ? $a : clone ($b);", "$r = $f ? $a : clone ($b);"},
		{"$r = $f ?clone ($a):$b;", "$r = $f ?clone $a :$b;"},
		{"$r = $a ?? clone ($b);", "$r = $a ?? clone ($b);"},
		{"$r = $f && clone ($a);", "$r = $f && clone ($a);"},
		{"$r = [clone ($a), clone ($b)];", "$r = [clone $a, clone $b];"},
		{"$r = [1, clone ($a), 2];", "$r = [1, clone $a, 2];"},
		{"$r = foo(clone ($a));", "$r = foo(clone $a);"},
		{"$r = foo(1, clone ($a));", "$r = foo(1, clone $a);"},
		{"$r = (clone ($a));", "$r = (clone $a);"},
		{"$r = fn () => clone ($a);", "$r = fn () => clone $a;"},
		{"$r = fn (): Foo => clone ($a);", "$r = fn (): Foo => clone $a;"},
		{"$r = fn (): array => clone ($a);", "$r = fn (): array => clone ($a);"},
		{"$r = fn (): ?Foo => clone ($a);", "$r = fn (): ?Foo => clone ($a);"},
		{"$r = fn (): A|B => clone ($a);", "$r = fn (): A|B => clone $a;"},
		{"$r = static fn &() => clone ($a);", "$r = static fn &() => clone $a;"},
		{"$o->p = clone ($a);", "$o->p = clone $a;"},
		{"$l[] = clone ($a);", "$l[] = clone $a;"},
		{"$r += clone ($a);", "$r += clone ($a);"},
		{"clone ($a);", "clone $a;"},
		{"clone ($a, ['x' => 1]);", "clone ($a, ['x' => 1]);"},
		{"echo clone ($a);", "echo clone $a;"},
		{"echo clone ($a ?: $b);", "echo clone ($a ?: $b);"},
		{"print clone ($a);", "print clone $a;"},
		{"return clone ($a);", "return clone $a;"},
		{"return clone ($a ?: $b);", "return clone ($a ?: $b);"},
		{"return clone ($a, ['x' => 1]);", "return clone ($a, ['x' => 1]);"},
		{"throw clone ($a);", "throw clone $a;"},
		{"yield clone ($a);", "yield clone $a;"},
		{"yield from clone ($a);", "yield from clone $a;"},
		{"for (clone ($a); clone ($b); clone ($c)) {}", "for (clone $a; clone $b; clone $c) {}"},
		{"if ($f) { clone ($a); }", "if ($f) { clone $a; }"},
		{"if ($f) { clone ($a); } clone ($b);", "if ($f) { clone $a; } clone $b;"},
		{"switch ($a) { case clone ($b): break; }", "switch ($a) { case clone $b : break; }"},
		{"$o->{'a'} = 1; clone ($a);", "$o->{'a'} = 1; clone $a;"},
		{"$r = $o->clone($a);", "$r = $o->clone($a);"},
		{"$r = $o?->clone($a);", "$r = $o?->clone($a);"},
		{"$r = Foo::clone($a);", "$r = Foo::clone($a);"},
		{"interface I { public function clone($a); }", "interface I { public function clone($a); }"},
		{"$r = clone /* c */ ($a);", "$r = clone /* c */ $a;"},
		{"$r = clone ( /* c */ $a);", "$r = clone  /* c */ $a;"},
		{"$r = clone ($a /* c */);", "$r = clone $a /* c */;"},
		{"$r = clone (\"x\");", "$r = clone \"x\";"},
		{"$r = clone (__CLASS__);", "$r = clone __CLASS__;"},
		{"$r = clone (static::foo());", "$r = clone static::foo();"},
		{"$r = clone ($a->b());", "$r = clone $a->b();"},
		{"$r = clone ($$a);", "$r = clone $$a;"},
		{"$r = clone ($a::class);", "$r = clone ($a::class);"},
		{"$r = clone (-$a);", "$r = clone (-$a);"},
		{"$r = clone ((object) $a);", "$r = clone ((object) $a);"},
		{"$r = clone (\"a$b\");", "$r = clone (\"a$b\");"},
		{"$r = clone ($a->class);", "$r = clone $a->class;"},
		{"$r = clone (1);", "$r = clone 1;"},
		{"switch ($a) { case 1: { } clone ($b); }", "switch ($a) { case 1: { } clone $b; }"},
		{"yield  from clone ($a);", "yield  from clone $a;"},
		{"yield\nfrom clone ($a);", "yield\nfrom clone $a;"},
		{"yield /* c */ from clone ($a);", "yield /* c */ from clone $a;"},
		{"$r = new (clone ($a));", "$r = new (clone $a);"},
		{"$x ? 1 : 2; if ($a): { } clone ($b); endif;", "$x ? 1 : 2; if ($a): { } clone ($b); endif;"},
		{"$x ? 1 : 2; switch ($a) { case 1: { } clone ($b); }", "$x ? 1 : 2; switch ($a) { case 1: { } clone $b; }"},
		{"Foo::{'a'}(); clone ($b);", "Foo::{'a'}(); clone $b;"},
		{"$r = clone (<<<'EOT'\nx\nEOT);", "$r = clone (<<<'EOT'\nx\nEOT);"},
		{"$r = clone (<<<EOT\nx\nEOT);", "$r = clone (<<<EOT\nx\nEOT);"},
		{"$r = clone (`ls`);", "$r = clone (`ls`);"},
		{"$r = clone (__PROPERTY__);", "$r = clone (__PROPERTY__);"},
		{"$r = clone (eval('x'));", "$r = clone (eval('x'));"},
		{"$r = clone (exit(1));", "$r = clone (exit(1));"},
		{"$r = clone (die());", "$r = clone (die());"},
		{"$r = clone (self::$a);", "$r = clone self::$a;"},
		{"$r = clone (parent::foo());", "$r = clone parent::foo();"},
		{"$r = clone (namespace\\foo());", "$r = clone (namespace\\foo());"},
		{"$r = clone (array(1));", "$r = clone (array(1));"},
		{"$r = clone (isset($a));", "$r = clone (isset($a));"},
		{"$r = clone (list($a) = $b);", "$r = clone (list($a) = $b);"},
		{"$r = clone (true);", "$r = clone true;"},
		{"$r = clone (function () {});", "$r = clone (function () {});"},
		{"$r = clone (fn () => 1);", "$r = clone (fn () => 1);"},
		{"$r = clone (match ($a) { 1 => 2 });", "$r = clone (match ($a) { 1 => 2 });"},
		{"$r = clone ($a->eval);", "$r = clone $a->eval;"},
		{"$r = clone ($a->namespace);", "$r = clone $a->namespace;"},
		{"$r = clone ($a?->exit());", "$r = clone $a?->exit();"},
		{"$r = clone (Foo::die());", "$r = clone Foo::die();"},
		{"$r = clone ($a->__PROPERTY__);", "$r = clone $a->__PROPERTY__;"},
		{"$r = clone ($a -> b);", "$r = clone $a -> b;"},
		{"$r = $f ? clone (object) $a : $b;", "$r = $f ? clone (object) $a : $b;"},
		{"$r = $f ? clone (object) ['a' => 1] : $b;", "$r = $f ? clone (object) ['a' => 1] : $b;"},
		{"$r = $f ? clone (int) $a : $b;", "$r = $f ? clone (int) $a : $b;"},
		{"clone (object) $a;", "clone (object) $a;"},
		{"$r = clone (App\\Namespace\\Foo::make());", "$r = clone App\\Namespace\\Foo::make();"},
		{"$r = clone (\\Foo\\die());", "$r = clone \\Foo\\die();"},
		{"$r = clone (Exit\\Foo::bar());", "$r = clone Exit\\Foo::bar();"},
		{"$r = clone (Foo\\Eval\\bar());", "$r = clone Foo\\Eval\\bar();"},
		{"$r = clone (Foo::/* c */die());", "$r = clone Foo::/* c */die();"},
		{"$r = clone (eval\\foo());", "$r = clone eval\\foo();"},
		{"$r = clone();", "$r = clone();"},
		{"$f ? clone() : 1;", "$f ? clone() : 1;"},
		{"$r = clone ($a) ?>", "$r = clone $a ?>"},
		{"clone ($a) ?>", "clone $a ?>"},
		{"?><?= clone ($a) ?>", "?><?= clone $a ?>"},
		{"foo(fn () => clone ($a), 1);", "foo(fn () => clone $a, 1);"},
		{"switch ($a) { case clone ($b); }", "switch ($a) { case clone $b; }"},
		{"$r = clone (\n    int\n);", "$r = clone \n    int\n;"},
		{"$r = $f ? clone ($a)->b : $c;", "$r = $f ? clone $a->b : $c;"},
		{"$r = $f ? clone ($a)[0] : $c;", "$r = $f ? clone $a[0] : $c;"},
		{"$r = $f ? clone ($a)?->b : $c;", "$r = $f ? clone $a?->b : $c;"},
		{"$r = $f ? clone ($a)::$b : $c;", "$r = $f ? clone $a ::$b : $c;"},
		{"$r = $f ? clone ($a)() : $c;", "$r = $f ? clone $a () : $c;"},
		{"$r = $f ? clone ($a) + 1 : $c;", "$r = $f ? clone $a + 1 : $c;"},
		{"$r = $f ? clone ($a) and $g : $c;", "$r = $f ? clone $a and $g : $c;"},
		{"$r = $f ? clone ($a) instanceof Foo : $c;", "$r = $f ? clone $a instanceof Foo : $c;"},
		{"$r = $f ? clone ($a) ?: 1 : $c;", "$r = $f ? clone $a ?: 1 : $c;"},
		{"$r = $f ? clone ( $a )->b : $c;", "$r = $f ? clone  $a ->b : $c;"},
		{"$r = $f ? clone (/* c */ $a)->b : $c;", "$r = $f ? clone /* c */ $a->b : $c;"},
		{"$r = $f ? clone (($a))->b : $c;", "$r = $f ? clone $a->b : $c;"},
		{"$r = $f ? clone ($this)->b : $c;", "$r = $f ? clone $this->b : $c;"},
		{"$r = $f ? clone ($a // c\n)->b : $c;", "$r = $f ? clone $a // c\n->b : $c;"},
		{"$r = $f ? clone ($a)?:1 : $c;", "$r = $f ? clone $a ?:1 : $c;"},
	}
	for _, c := range cases {
		got, changed := apply(t, NoUnneededControlParentheses{}, "<?php\n"+c.src+"\n")
		if want := "<?php\n" + c.want + "\n"; got != want || changed != (c.src != c.want) {
			t.Errorf("%s\n got=%q changed=%v\nwant=%q", c.src, got, changed, want)
		}
	}
}
