package rules

import "testing"

// Cases ported from PHP-CS-Fixer's CommentToPhpdocFixerTest (tests/Fixer/Comment);
// every expected output is what PHP-CS-Fixer produces for the input.
func TestCommentToPhpdocPhpCsFixerCases(t *testing.T) {
	t.Parallel()
	todo := map[string]any{"ignored_tags": []string{"todo"}}
	aliasRunUpstreamCases(t, CommentToPhpdoc{}, []aliasUpstreamCase{
		{"header comment and no tag", nil,
			`<?php /* header comment */ $foo = true; /* string $bar */ $bar = "baz";`,
			`<?php /* header comment */ $foo = true; /* string $bar */ $bar = "baz";`},
		{"tag not at line start, yoda", nil,
			`<?php /* header comment */ $foo = true; /* $yoda string @var */`,
			`<?php /* header comment */ $foo = true; /* $yoda string @var */`},
		{"tag not at line start, yoda 2", nil,
			`<?php /* header comment */ $foo = true; /* $yoda @var string */`,
			`<?php /* header comment */ $foo = true; /* $yoda @var string */`},
		{"single block", nil,
			`<?php /* header comment */ $foo = true; /* @var string $bar */ $bar = "baz";`,
			`<?php /* header comment */ $foo = true; /** @var string $bar */ $bar = "baz";`},
		{"single block no space", nil,
			`<?php /* header comment */ $foo = true; /*@var string $bar */ $bar = "baz";`,
			`<?php /* header comment */ $foo = true; /** @var string $bar */ $bar = "baz";`},
		{"triple asterisk opener", nil,
			"<?php /* header comment */ $foo = true;\n                /*** @var string $bar */\n                $bar = \"baz\";\n                ",
			"<?php /* header comment */ $foo = true;\n                /** @var string $bar */\n                $bar = \"baz\";\n                "},
		{"double slash with space", nil,
			"<?php /* header comment */ $foo = true;\n                // @var string $bar\n                $bar = \"baz\";\n                ",
			"<?php /* header comment */ $foo = true;\n                /** @var string $bar */\n                $bar = \"baz\";\n                "},
		{"double slash no space", nil,
			"<?php /* header comment */ $foo = true;\n                //@var string $bar\n                $bar = \"baz\";\n                ",
			"<?php /* header comment */ $foo = true;\n                /** @var string $bar */\n                $bar = \"baz\";\n                "},
		{"hash with space", nil,
			"<?php /* header comment */ $foo = true;\n                # @var string $bar\n                $bar = \"baz\";\n                ",
			"<?php /* header comment */ $foo = true;\n                /** @var string $bar */\n                $bar = \"baz\";\n                "},
		{"hash no space", nil,
			"<?php /* header comment */ $foo = true;\n                #@var string $bar\n                $bar = \"baz\";\n                ",
			"<?php /* header comment */ $foo = true;\n                /** @var string $bar */\n                $bar = \"baz\";\n                "},
		{"multi-line block", nil,
			"<?php /* header comment */ $foo = true;\n\n/*\n * @var string $bar\n */\n$bar = \"baz\";",
			"<?php /* header comment */ $foo = true;\n\n/**\n * @var string $bar\n */\n$bar = \"baz\";"},
		{"multi-line double slash", nil,
			"<?php /* header comment */ $foo = true;\n\n// This is my var\n// @var string $foo\n// stop using it\n// @deprecated since 1.2\n$foo = 1;",
			"<?php /* header comment */ $foo = true;\n\n/**\n * This is my var\n * @var string $foo\n * stop using it\n * @deprecated since 1.2\n */\n$foo = 1;"},
		{"inside for, double slash", nil,
			"<?php /* header comment */ $foo = true;\n\nfor (;;) {\n    // This is my var\n    // @var string $foo\n    $foo = someValue();\n}",
			"<?php /* header comment */ $foo = true;\n\nfor (;;) {\n    /**\n     * This is my var\n     * @var string $foo\n     */\n    $foo = someValue();\n}"},
		{"multi-line hash", nil,
			"<?php /* header comment */ $foo = true;\n\n# This is my var\n# @var string $foo\n# stop using it\n# @deprecated since 1.3\n$foo = 1;",
			"<?php /* header comment */ $foo = true;\n\n/**\n * This is my var\n * @var string $foo\n * stop using it\n * @deprecated since 1.3\n */\n$foo = 1;"},
		{"doctrine column", nil,
			"<?php /* header comment */ $foo = true;\n\n/*\n * @Column(type=\"string\", length=32, unique=true, nullable=false)\n */\n$bar = 'baz';",
			"<?php /* header comment */ $foo = true;\n\n/**\n * @Column(type=\"string\", length=32, unique=true, nullable=false)\n */\n$bar = 'baz';"},
		{"orm column namespaced tag", nil,
			"<?php /* header comment */ $foo = true;\n\n/*\n * @ORM\\Column(name=\"id\", type=\"integer\")\n */\n$bar = 42;",
			"<?php /* header comment */ $foo = true;\n\n/**\n * @ORM\\Column(name=\"id\", type=\"integer\")\n */\n$bar = 42;"},
		{"nested close kept as comment", nil,
			"<?php /* header comment */ $foo = true;\n\n// This is my var\n// /** @var string $foo */\n$foo = 1;",
			"<?php /* header comment */ $foo = true;\n\n// This is my var\n// /** @var string $foo */\n$foo = 1;"},
		{"ignored todo single", todo,
			"<?php /* header comment */ $foo = true;\n\n// @todo do something later\n$foo = 1;",
			"<?php /* header comment */ $foo = true;\n\n// @todo do something later\n$foo = 1;"},
		{"ignored todo uppercase", todo,
			"<?php /* header comment */ $foo = true;\n\n// @TODO do something later\n$foo = 1;",
			"<?php /* header comment */ $foo = true;\n\n// @TODO do something later\n$foo = 1;"},
		{"ignored todo then var", todo,
			"<?php /* header comment */ $foo = true;\n\n// @todo do something later\n// @var int $foo\n$foo = 1;",
			"<?php /* header comment */ $foo = true;\n\n/**\n * @todo do something later\n * @var int $foo\n */\n$foo = 1;"},
		{"var then ignored todo", todo,
			"<?php /* header comment */ $foo = true;\n\n// @var int $foo\n// @todo do something later\n$foo = 1;",
			"<?php /* header comment */ $foo = true;\n\n/**\n * @var int $foo\n * @todo do something later\n */\n$foo = 1;"},
		{"slash slash slash before namespace", nil,
			"<?php // header\n                ///@foo\n                namespace Foo\\Bar;\n",
			"<?php // header\n                /** /@foo */\n                namespace Foo\\Bar;\n"},
		{"triple slash block before namespace", nil,
			"<?php // header\n                /// @foo\n                /// @bar\n                namespace Foo\\Bar;\n",
			"<?php // header\n                /**\n                 * / @foo\n                 * / @bar\n                 */\n                namespace Foo\\Bar;\n"},
		{"phpstan-use on trait use", nil,
			`<?php /* header comment */ $foo = true; class Foo { /* @phpstan-use Bar<Baz> $bar */ use Bar; }`,
			`<?php /* header comment */ $foo = true; class Foo { /** @phpstan-use Bar<Baz> $bar */ use Bar; }`},
		{"phpstan-ignore skipped, next converted", nil,
			"<?php\n            $foo = new class extends Foo { // @phpstan-ignore method.internal\n                // @foo\n                public function m(): void {}\n            };\n",
			"<?php\n            $foo = new class extends Foo { // @phpstan-ignore method.internal\n                /** @foo */\n                public function m(): void {}\n            };\n"},
		{"psalm-suppress skipped, next converted", nil,
			"<?php\n            $foo = new class extends Foo { // @psalm-suppress all\n                // @foo\n                public function m(): void {}\n            };\n",
			"<?php\n            $foo = new class extends Foo { // @psalm-suppress all\n                /** @foo */\n                public function m(): void {}\n            };\n"},
		{"phpstan-return not suppressed", nil,
			"<?php\n$foo = new class extends Foo { // @phpstan-return void\n    // @foo\n    public function m(): void {}\n};",
			"<?php\n$foo = new class extends Foo { /**\n * @phpstan-return void\n * @foo\n */\n    public function m(): void {}\n};"},
		{"asymmetric visibility", nil,
			"<?php class Foo {\n    /* @var int */\n    public(set) int $a;\n    /* @var int */\n    protected(set) int $b;\n    /* @var int */\n    private(set) int $c;\n}",
			"<?php class Foo {\n    /** @var int */\n    public(set) int $a;\n    /** @var int */\n    protected(set) int $b;\n    /** @var int */\n    private(set) int $c;\n}"},
	})
}
