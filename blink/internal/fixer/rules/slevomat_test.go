package rules

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/ecsphp/ecs-src/blink/internal/fixer"
	"github.com/ecsphp/ecs-src/blink/internal/lexer"
	"github.com/ecsphp/ecs-src/blink/internal/tokens"
)

type slevomatCase struct {
	Sniff  string         `json:"sniff"`
	File   string         `json:"file"`
	Config map[string]any `json:"config"`
	// Variant names the expected output of a fixture that runs with several configs.
	Variant string `json:"variant"`
	// Unstable marks a fixture where a second ECS run changes the output further.
	Unstable bool `json:"unstable"`
}

func (c slevomatCase) baseName() string {
	name := strings.TrimSuffix(c.File, ".php")
	if c.Variant != "" {
		name += "." + c.Variant
	}
	return name
}

func (c slevomatCase) expectedFile() string { return c.baseName() + ".fixed.php" }

// TestSlevomatFixtures runs every slevomat sniff port on the upstream test
// fixtures; the expected output (.fixed.php, absent when nothing changes) and
// the errors of a report-only sniff (.errors, absent when there are none) are
// what ECS produces, regenerated by bin/slevomat-golden.php.
func TestSlevomatFixtures(t *testing.T) {
	t.Parallel()
	dir := filepath.Join("testdata", "slevomat")
	raw, err := os.ReadFile(filepath.Join(dir, "cases.json"))
	if err != nil {
		t.Fatal(err)
	}
	var cases []slevomatCase
	if err := json.Unmarshal(raw, &cases); err != nil {
		t.Fatal(err)
	}
	for _, c := range cases {
		t.Run(c.baseName(), func(t *testing.T) {
			t.Parallel()
			f, ok := ByName(c.Sniff)
			if !ok {
				t.Fatalf("%s is not registered", c.Sniff)
			}
			if c.Config != nil {
				configurable, ok := f.(fixer.ConfigurableFixer)
				if !ok {
					t.Fatalf("%s takes no configuration", c.Sniff)
				}
				f = configurable.WithConfig(c.Config)
			}
			input := readFixture(t, filepath.Join(dir, c.File))
			if reporter, ok := f.(fixer.ErrorReporter); ok {
				var want []string
				if raw, err := os.ReadFile(filepath.Join(dir, c.baseName()+".errors")); err == nil {
					want = strings.Split(strings.TrimSuffix(string(raw), "\n"), "\n")
				}
				var got []string
				for _, e := range reporter.Errors(tokens.New(lexer.Lex(input))) {
					got = append(got, phpcsErrorRow(e))
				}
				if !slices.Equal(got, want) {
					t.Fatalf("%s errors:\nwant %q\ngot  %q", c.Sniff, want, got)
				}
			}
			expected := input
			if fixed, err := os.ReadFile(filepath.Join(dir, c.expectedFile())); err == nil {
				expected = string(fixed)
			}
			got, changed := apply(t, f, input)
			if got != expected {
				t.Fatalf("%s:\n%s", c.Sniff, lineDiff(expected, got))
			}
			if changed != (input != expected) {
				t.Errorf("changed=%v, want %v", changed, input != expected)
			}
			if c.Unstable {
				return
			}
			if again, changed := apply(t, f, expected); changed || again != expected {
				t.Errorf("expected output is not stable:\n%s", lineDiff(expected, again))
			}
		})
	}
}

// lineDiff lists the lines where got differs from want.
func lineDiff(want, got string) string {
	w, g := strings.Split(want, "\n"), strings.Split(got, "\n")
	var b strings.Builder
	for i := range max(len(w), len(g)) {
		var wl, gl string
		if i < len(w) {
			wl = w[i]
		}
		if i < len(g) {
			gl = g[i]
		}
		if wl != gl {
			fmt.Fprintf(&b, "line %d:\n  want: %q\n  got:  %q\n", i+1, wl, gl)
		}
	}
	return b.String()
}
